// EduQuest Phase 7 — step 5.4: generate and bundle the actual per-role
// entry points, using build/compute-role-split.js's closure data.
//
// SAFETY POLICY, stated explicitly rather than silently applied:
// - Files in `neither` (unattributed by the closure computation — 5 of
//   them: error-capture.js, index.html#inline0, modules/admin/
//   analytics.js, modules/admin/teacher-invite-service.js, recovery.js)
//   are added to BOTH bundles. Over-inclusion is a safe failure mode
//   (unused code shipped, bundle slightly larger than optimal);
//   under-inclusion is not (a missing file throws at runtime, per every
//   real bug session 8 found). When genuinely unsure, include.
// - The external CDN script (@supabase/supabase-js) is not part of
//   either bundle — stays a real <script src> tag in the shipped page,
//   loaded before either bundle, same as today.
// - Known remaining imperfection, documented rather than hidden: boss-
//   studio's 2 true sink files (bs_editor.js, bs_index.js) land in BOTH
//   bundles even though they're really admin-only, because 3 of the
//   directory's 4 real files (the shared rendering engine/storage/
//   animation library) are genuinely needed by student battle code too,
//   and the majority-based attribution heuristic can't cleanly separate
//   "borrows one shared utility" from "needs the whole feature" for a
//   directory this internally mixed. Costs a small amount of unused code
//   in the student bundle; does not affect correctness.

const fs = require('fs');
const path = require('path');
const { getOrderedScriptElements } = require('./lib/analyze-unit');

const ROOT = path.join(__dirname, '..');

function main() {
  const split = JSON.parse(fs.readFileSync(path.join(ROOT, 'dist', 'role-split.json'), 'utf8'));
  const safeDefaultShared = new Set([...split.neitherRole, 'modules/shared/presentation.js', 'modules/rewards/learning-rewards.js', 'modules/quests/study-studio.js']);

  const studentSet = new Set([...split.shared, ...split.studentOnly, ...safeDefaultShared]);
  const adminSet = new Set([...split.shared, ...split.adminOnly, ...safeDefaultShared, 'modules/seat-arrangement/classroom-editor.js']);

  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const elements = getOrderedScriptElements(html);

  function buildEntry(roleName, roleSet) {
    const lines = [
      `// AUTO-GENERATED by build/generate-role-entries.js for role: ${roleName}`,
      `// Do not hand-edit. Regenerate after any role-split or index.html change.`,
      '',
    ];
    let inlineIdx = 0;
    let included = 0;
    let excluded = 0;
    for (const el of elements) {
      if (el.type === 'external') {
        if (!el.src.startsWith('./')) continue; // CDN, stays as a real script tag
        const rel = el.src.replace(/^\.\//, '');
        if (roleSet.has(rel)) {
          lines.push(`import '../${rel}';`);
          included++;
        } else {
          excluded++;
        }
      } else {
        const label = `index.html#inline${inlineIdx}`;
        if (roleSet.has(label)) {
          lines.push(`import './inline/inline${inlineIdx}.js';`);
          included++;
        } else {
          excluded++;
        }
        inlineIdx++;
      }
    }
    const entryPath = path.join(ROOT, 'build', `entry.${roleName}.js`);
    fs.writeFileSync(entryPath, lines.join('\n') + '\n');
    console.log(`${roleName}: ${included} included, ${excluded} excluded -> ${entryPath}`);
    return entryPath;
  }

  buildEntry('student', studentSet);
  buildEntry('admin', adminSet);
}

main();
