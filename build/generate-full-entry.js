// EduQuest Phase 7 — step 5.4 precursor: the first REAL full-app bundle.
//
// Unlike build/concat.js (raw text concatenation, no real scoping — the
// zero-source-change safety net from session 1), this generates a real
// esbuild entry point: every unit gets an actual `import` statement, so
// esbuild scope-wraps each one for real. This only became safe to attempt
// after session 7's window-export audit closed the 180-symbol gap between
// "works because of implicit classic-script scope" and "works because of
// an explicit window export."
//
// For every unit still living at its original classic-script location:
// `import './path.js';` (side-effect import — declarations get scope-
// wrapped, but every one with a real consumer now has an explicit
// `window.X =`, so nothing breaks).
//
// For every unit that's been converted to src/ (currently: dom.js only):
// a real `import { a, b } from '../src/dom.js';` followed by explicit
// `window.a = a; window.b = b;` — the same bridge pattern proven in
// session 6, generated here instead of hand-written.

const fs = require('fs');
const path = require('path');
const { getOrderedScriptElements, analyzeUnit } = require('./lib/analyze-unit');

const ROOT = path.join(__dirname, '..');
const ENTRY_OUT = path.join(ROOT, 'build', 'entry.full.js');
const BUNDLE_OUT = path.join(ROOT, 'dist', 'app.full-bundle.js');

// Map of original classic-file relative path -> src/ conversion info.
// Extend this as more files get converted (session 5+ pattern).
const CONVERTED = {
  'dom.js': { srcPath: '../src/dom.js', exports: ['toast', 'showModal', 'closeModal', 'closeModalForce'] },
};

function main() {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const elements = getOrderedScriptElements(html);

  const lines = [
    '// AUTO-GENERATED by build/generate-full-entry.js — do not hand-edit.',
    '// Regenerate after any index.html script-order change or src/ conversion.',
    '',
  ];
  let inlineIdx = 0;
  let convertedCount = 0;
  let classicCount = 0;

  for (const el of elements) {
    if (el.type === 'external') {
      if (!el.src.startsWith('./')) {
        lines.push(`// external CDN script (${el.src}) — stays as a real <script src> tag`);
        lines.push(`// in the shipped page, loaded before this bundle. Not imported here.`);
        continue;
      }
      const rel = el.src.replace(/^\.\//, '');
      if (CONVERTED[rel]) {
        const conv = CONVERTED[rel];
        lines.push(`// ${rel} — CONVERTED, real import + window bridge`);
        lines.push(`import { ${conv.exports.join(', ')} } from '${conv.srcPath}';`);
        for (const name of conv.exports) lines.push(`window.${name} = ${name};`);
        convertedCount++;
      } else {
        lines.push(`import '../${rel}';`);
        classicCount++;
      }
    } else {
      // inline <script> blocks can't be `import`ed as separate files —
      // write them out to a temp file under build/inline/ and import that,
      // so they still get real module scoping like everything else.
      const outDir = path.join(ROOT, 'build', 'inline');
      fs.mkdirSync(outDir, { recursive: true });
      const inlineFile = path.join(outDir, `inline${inlineIdx}.js`);
      fs.writeFileSync(inlineFile, el.code);
      lines.push(`import './inline/inline${inlineIdx}.js';`);
      inlineIdx++;
      classicCount++;
    }
  }

  fs.writeFileSync(ENTRY_OUT, lines.join('\n') + '\n');
  console.log(`Wrote ${ENTRY_OUT}`);
  console.log(`  converted (real import+bridge): ${convertedCount}`);
  console.log(`  classic (side-effect import): ${classicCount}`);
  console.log(`  inline blocks extracted to build/inline/: ${inlineIdx}`);
}

main();
